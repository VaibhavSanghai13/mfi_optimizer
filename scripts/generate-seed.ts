/**
 * bcrypt normally uses a random salt, which would make seed.sql different on every
 * run. Demo accounts get a salt derived from their email instead, so the file is
 * reproducible. Real users (created in the app) always get random salts.
 */
function hashPassword(password: string, email: string): string {
  const alphabet = './ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789'
  const rand = seededRandom(fnv1a(email))
  const salt = '$2b$10$' + Array.from({ length: 22 }, () => alphabet[Math.floor(rand() * alphabet.length)]).join('')
  return bcrypt.hashSync(password, salt)
}

/** Small string hash used to seed the salt generator. */
function fnv1a(text: string): number {
  let hash = 0x811c9dc5
  for (const char of text) hash = Math.imul(hash ^ char.charCodeAt(0), 0x01000193)
  return hash >>> 0
}

/** Turns a JS value into a SQL literal. Strings are quoted with ' escaped as ''. */
function literal(value: unknown): string {
  if (value === null || value === undefined) return 'null'
  if (typeof value === 'number' || typeof value === 'boolean') return String(value)
  return `'${String(value).replace(/'/g, "''")}'`
}

/** One multi-row `insert … on conflict do nothing` statement. */
function insert(table: string, rows: Record<string, unknown>[]): string {
  const columns = Object.keys(rows[0])
  const values = rows.map((row) => `  (${columns.map((c) => literal(row[c])).join(', ')})`).join(',\n')
  return `insert into ${table} (${columns.join(', ')}) values\n${values}\non conflict do nothing;\n`
}
